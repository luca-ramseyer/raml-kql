#!/usr/bin/env node
/**
 * Imports VS Code's default colour themes (MIT licensed) and flattens their `include` chains
 * into self-contained theme files the app ships with.
 *
 * This is a maintainer tool, run by hand when updating to a newer VS Code release. It is the
 * only script that touches the network; the output is committed and reviewed like code.
 *
 * Usage: node scripts/import-vscode-themes.mjs [vscode-tag]   (default: the pinned tag below)
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { parse, printParseErrorCode } from 'jsonc-parser';

const VSCODE_TAG = process.argv[2] ?? '1.139.0';
const BASE = `https://raw.githubusercontent.com/microsoft/vscode/${VSCODE_TAG}/extensions/theme-defaults/themes/`;
const OUT_DIR = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../apps/desktop/src/renderer/platform/theme/builtin',
);

/** App theme id → VS Code file and base UI theme (VS Code's `uiTheme`). */
const THEMES = [
  {
    id: 'default-dark-modern',
    label: 'Default Dark Modern',
    file: 'dark_modern.json',
    uiTheme: 'vs-dark',
  },
  {
    id: 'default-light-modern',
    label: 'Default Light Modern',
    file: 'light_modern.json',
    uiTheme: 'vs',
  },
  {
    id: 'default-high-contrast',
    label: 'Default High Contrast',
    file: 'hc_black.json',
    uiTheme: 'hc-black',
  },
  {
    id: 'default-high-contrast-light',
    label: 'Default High Contrast Light',
    file: 'hc_light.json',
    uiTheme: 'hc-light',
  },
];

async function load(file) {
  const response = await fetch(BASE + file);
  if (!response.ok) throw new Error(`GET ${file}: HTTP ${response.status}`);
  const errors = [];
  const json = parse(await response.text(), errors, { allowTrailingComma: true });
  if (errors.length > 0) {
    throw new Error(`${file}: ${errors.map((e) => printParseErrorCode(e.error)).join(', ')}`);
  }
  return json;
}

/** Resolve `include` recursively: parents first, children override. */
async function flatten(file, depth = 0) {
  if (depth > 5) throw new Error(`include chain too deep at ${file}`);
  const theme = await load(file);
  const parent = theme.include ? await flatten(path.posix.basename(theme.include), depth + 1) : {};
  return {
    colors: { ...parent.colors, ...theme.colors },
    tokenColors: [...(parent.tokenColors ?? []), ...(theme.tokenColors ?? [])],
    semanticHighlighting: theme.semanticHighlighting ?? parent.semanticHighlighting,
    semanticTokenColors: { ...parent.semanticTokenColors, ...theme.semanticTokenColors },
  };
}

mkdirSync(OUT_DIR, { recursive: true });
for (const { id, label, file, uiTheme } of THEMES) {
  const flat = await flatten(file);
  const output = {
    $comment: `Generated by scripts/import-vscode-themes.mjs from microsoft/vscode@${VSCODE_TAG} extensions/theme-defaults/themes/${file} (MIT License, Copyright (c) Microsoft Corporation). Do not edit by hand.`,
    id,
    label,
    uiTheme,
    ...flat,
  };
  writeFileSync(path.join(OUT_DIR, `${id}.json`), JSON.stringify(output, null, 2) + '\n');
  console.log(
    `${id}: ${Object.keys(flat.colors).length} colours, ${flat.tokenColors.length} token rules`,
  );
}
