// Not useful to readers: development-only or internal to one popup.
const HIDDEN = new Set([
  'workbench.action.reloadWindow',
  'workbench.action.closeQuickOpen',
  'notifications.hideToasts',
]);

function pretty(key) {
  return key
    .split(' ')
    .map((chord) =>
      chord
        .split('+')
        .map((part) => {
          const names = {
            cmd: '⌘',
            ctrl: 'Ctrl',
            alt: 'Alt',
            shift: 'Shift',
            enter: 'Enter',
            escape: 'Esc',
            tab: 'Tab',
            numpad0: 'Numpad 0',
            f1: 'F1',
            f11: 'F11',
          };
          return names[part] ?? part.toUpperCase();
        })
        .join('+'),
    )
    .join(' ');
}

function shortcutsPage(bindings) {
  const groups = new Map();
  for (const binding of bindings) {
    if (HIDDEN.has(binding.command)) continue;
    const [group, label] = LABELS[binding.command] ?? ['Other', binding.command];
    if (!groups.has(group)) groups.set(group, new Map());
    const rows = groups.get(group);
    const row = rows.get(binding.command) ?? { label, mac: [], other: [] };
    const push = (list, key) => {
      if (!list.includes(key)) list.push(key);
    };
    push(row.mac, pretty(binding.mac ?? binding.key));
    push(row.other, pretty(binding.win ?? binding.linux ?? binding.key));
    rows.set(binding.command, row);
  }
  const lines = [
    '---',
    'title: Keyboard shortcuts',
    'description: The default keyboard shortcuts, and how to change them.',
    '---',
    '',
    GENERATED,
    '',
    '# Keyboard shortcuts',
    '',
    'Raml KQL uses VS Code shortcuts wherever the same action exists. Change or remove any of them in `keybindings.jsonc` (**Preferences: Open Keyboard Shortcuts (JSON)**, <kbd>Ctrl/Cmd</kbd>+<kbd>K</kbd> <kbd>Ctrl/Cmd</kbd>+<kbd>S</kbd>), which uses the same format as VS Code:',
    '',
    '```jsonc',
    '[',
    '  { "key": "ctrl+shift+r", "command": "query.run" },',
    '  // A leading "-" removes a default shortcut:',
    '  { "key": "shift+enter", "command": "-query.run" }',
    ']',
    '```',
    '',
    'A few actions have more than one shortcut; all are listed. The Command Palette (<kbd>F1</kbd>) lists every command, including those without a shortcut.',
    '',
  ];
  for (const [group, rows] of groups) {
    lines.push(`## ${group}`, '', '| Action | macOS | Windows and Linux |', '| --- | --- | --- |');
    for (const [command, row] of rows) {
      lines.push(
        `| ${row.label} (\`${command}\`) | ${row.mac.join(' or ')} | ${row.other.join(' or ')} |`,
      );
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

const { settingDefinitions, z } = await load('apps/desktop/src/shared/settings/registry.ts');
const { DEFAULT_KEYBINDINGS } = await load('apps/desktop/src/shared/keybindings/keybindings.ts');

const outputs = {
  'docs/reference/settings.md': await format(
    settingsPage(settingDefinitions, z),
    'docs/reference/settings.md',
  ),
  'docs/reference/keyboard-shortcuts.md': await format(
    shortcutsPage(DEFAULT_KEYBINDINGS),
    'docs/reference/keyboard-shortcuts.md',
  ),
};

let stale = false;
for (const [file, content] of Object.entries(outputs)) {
  const target = path.join(root, file);
  if (check) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      // Missing counts as stale.
    }
    if (current !== content) {
      console.error(`${file} is out of date. Run: pnpm docs:generate`);
      stale = true;
    }
  } else {
    writeFileSync(target, content);
    console.log(`Wrote ${file}`);
  }
}
if (stale) process.exit(1);
