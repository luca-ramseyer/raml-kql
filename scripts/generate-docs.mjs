// Generates the reference pages that must never drift from the code:
//   docs/reference/settings.md           from the settings registry
//   docs/reference/keyboard-shortcuts.md from the default keybindings
//
//   node scripts/generate-docs.mjs          write the files
//   node scripts/generate-docs.mjs --check  fail if they are out of date (used by CI)
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { build } from 'esbuild';
import * as prettier from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

/**
 * Bundle a TypeScript module of the app so this script can import it. `zod` is re-exported
 * from the same bundle, so schemas and `toJSONSchema` come from one copy of the library.
 */
async function load(entry) {
  const dir = mkdtempSync(path.join(tmpdir(), 'raml-kql-docs-'));
  const outfile = path.join(dir, 'module.mjs');
  const desktop = path.join(root, 'apps', 'desktop');
  try {
    await build({
      stdin: {
        contents: `export * from ${JSON.stringify(path.join(root, entry))};\nexport { z } from 'zod';`,
        resolveDir: desktop,
        loader: 'ts',
      },
      outfile,
      bundle: true,
      format: 'esm',
      platform: 'node',
      logLevel: 'error',
    });
    return await import(pathToFileURL(outfile).href);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

async function format(markdown, file) {
  const options = (await prettier.resolveConfig(path.join(root, file))) ?? {};
  return prettier.format(markdown, { ...options, parser: 'markdown' });
}

const GENERATED =
  '<!-- Generated by scripts/generate-docs.mjs. Do not edit by hand: run `pnpm docs:generate`. -->';

function inline(value) {
  return `\`${JSON.stringify(value)}\``;
}

function describeType(definition, z) {
  const { control, schema } = definition;
  let json = {};
  try {
    json = z.toJSONSchema(schema, { unrepresentable: 'any' });
  } catch {
    // Fall through: the control kind alone says enough.
  }
  switch (control.kind) {
    case 'boolean':
      return 'boolean';
    case 'colorTheme':
      return 'string (the name of a colour theme)';
    case 'string':
      return 'string';
    case 'number': {
      const range = [];
      if (json.minimum !== undefined) range.push(`at least ${json.minimum}`);
      if (json.maximum !== undefined) range.push(`at most ${json.maximum}`);
      const kind = json.type === 'integer' ? 'integer' : 'number';
      return range.length > 0 ? `${kind}, ${range.join(', ')}` : kind;
    }
    case 'enum':
      return `one of ${control.options.map((o) => inline(o)).join(', ')}`;
    default:
      return 'JSON (edit it in `settings.jsonc`)';
  }
}

function settingsPage(definitions, z) {
  const byCategory = new Map();
  for (const definition of definitions) {
    const category = definition.category.join(' › ');
    if (!byCategory.has(category)) byCategory.set(category, []);
    byCategory.get(category).push(definition);
  }
  const lines = [
    '---',
    'title: Settings reference',
    'description: Every Raml KQL setting, with its type, default and what it does.',
    '---',
    '',
    GENERATED,
    '',
    '# Settings reference',
    '',
    'Settings live in `settings.jsonc` in the [configuration folder](config-files.md) and can be changed in the Settings editor (<kbd>Ctrl/Cmd</kbd>+<kbd>,</kbd>). The file is JSON with comments, and changes apply as soon as you save it.',
    '',
  ];
  for (const [category, items] of [...byCategory].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`## ${category}`, '');
    for (const definition of items) {
      lines.push(`### \`${definition.key}\``, '', definition.description, '');
      lines.push(`- **Type:** ${describeType(definition, z)}`);
      lines.push(`- **Default:** ${inline(definition.default)}`);
      if (definition.control.kind === 'enum' && definition.control.optionDescriptions) {
        definition.control.options.forEach((option, index) => {
          const text = definition.control.optionDescriptions[index];
          if (text) lines.push(`  - ${inline(option)}: ${text}`);
        });
      }
      lines.push('');
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

